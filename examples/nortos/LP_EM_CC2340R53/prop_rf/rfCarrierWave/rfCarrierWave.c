/***** Includes *****/
/* Standard C Libraries */
#include <stdlib.h>
#include <stdio.h>
#include <unistd.h>

/* TI Drivers */
#include <ti/drivers/RCL.h>
#include <ti/drivers/rcl/RCL_Scheduler.h>
#include <ti/drivers/rcl/commands/generic.h>

/* SysConfig Generated */
#include "ti_drivers_config.h"
#include "ti_radio_config.h"

/***** Defines *****/
/* RF Frequency (Hz) to program */
#define FREQUENCY               (2440000000U)
/* TX output power integer part (signed value) */
#define TX_POWER_DBM            (5)
/* TX output power fractional part (1 to increase the TX output power by 0.5 dB) */
#define TX_POWER_FRACTION       (0)
/* TX duration in milliseconds, 0 = infinite (if used, reset device to restart TX) */
#define TX_DURATION_MS          (0)

/***** Variable Declarations *****/
/* RCL Commands */
/* Generate the command for continuous TX manually, since this is not provided
 * in the ti_radio_config.c file generated by SysConfig. Please modify the
 * FREQUENCY, TX_POWER_DBM, TX_POWER_FRACTION and definitions above to configure
 * the command.
 */
static RCL_CmdGenericTxTest rclContTxCmdGenericTxTest = RCL_CmdGenericTxTest_Default();

/* Wanted TX output power */
RCL_Command_TxPower wantedTxPower =
{
    .dBm = TX_POWER_DBM,
    .fraction = TX_POWER_FRACTION
};

/* RCL Client used to open RCL */
static RCL_Client rclClient;

/***** Callback functions *****/
void defaultCallback(RCL_Command *cmd, LRF_Events lrfEvents, RCL_Events rclEvents)
{
    if (rclEvents.lastCmdDone)
    {
        /* Will get this callback when TX_DURATION_MS expires */
    }
}

/***** Function definitions *****/

void *mainThread(void *arg0)
{
    /* Initialize and open RCL */
    RCL_init();
    RCL_Handle rclHandle = RCL_open(&rclClient, &LRF_config);

    /* Ensure that the specified TX power matches a PA table entry (round down) */
    RCL_Command_TxPower validTxPower = RCL_txPowerLookup(&LRF_txPowerTable, wantedTxPower, false, true);

    /* Set RF frequency */
    rclContTxCmdGenericTxTest.rfFrequency = FREQUENCY;
    rclContTxCmdGenericTxTest.txPower.rawValue = validTxPower.rawValue;

    /* Start command as soon as possible */
    rclContTxCmdGenericTxTest.common.scheduling = RCL_Schedule_Now;
    rclContTxCmdGenericTxTest.common.status = RCL_CommandStatus_Idle;
    rclContTxCmdGenericTxTest.common.timing.relHardStopTime = RCL_SCHEDULER_SYSTIM_MS(TX_DURATION_MS);

    rclContTxCmdGenericTxTest.config.sendCw = 1U;       // Transmit unmodulated signal
    rclContTxCmdGenericTxTest.config.whitenMode = 1U;   // Default whitening
    rclContTxCmdGenericTxTest.config.txWord = 0U;       // Repeated word to transmit
    rclContTxCmdGenericTxTest.config.fsOff = 1;         // Turn off FS

    /* Callback triggers on last command done */
    rclContTxCmdGenericTxTest.common.runtime.callback = defaultCallback;
    rclContTxCmdGenericTxTest.common.runtime.rclCallbackMask.value = RCL_EventLastCmdDone.value;

    /* Submit command */
    RCL_Command_submit(rclHandle, &rclContTxCmdGenericTxTest);

    /* Wait for the command to be stopped when TX_DURATION_MS expires, then wait forever */
    RCL_Command_pend(&rclPacketTxCmdGenericTxTest);
    while (1)
    {
    }
}
