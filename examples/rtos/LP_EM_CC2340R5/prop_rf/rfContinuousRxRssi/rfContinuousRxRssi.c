/***** Includes *****/
/* Standard C Libraries */
#include <stdlib.h>
#include <stdio.h>
#include <unistd.h>
#include <string.h>

/* TI Drivers */
#include <ti/drivers/UART2.h>
#include <ti/drivers/RCL.h>
#include <ti/drivers/rcl/RCL_Scheduler.h>
#include <ti/drivers/rcl/commands/generic.h>

/* SysConfig Generated */
#include "ti_drivers_config.h"
#include "ti_radio_config.h"

/***** Defines *****/
/* RF Frequency (Hz) to program */
#define FREQUENCY               (2440000000U)
/* RSSI output interval (added delay between iterations), in microseconds */
#define RSSI_INTERVAL_US        (100000U)

/***** Variable Declarations *****/
/* RCL Commands */
/* Generate the command for continuous RX manually, since this is not provided
 * in the ti_radio_config.c file generated by SysConfig. Please modify the
 * FREQUENCY definition above to configure the command.
 */
static RCL_CmdGenericRx rclContRxCmdGenericRx = RCL_CmdGenericRx_Default();

/* RCL Client used to open RCL */
static RCL_Client rclClient;

/***** Callback functions *****/
void defaultCallback(RCL_Command *cmd, LRF_Events lrfEvents, RCL_Events rclEvents)
{
}

/***** Function definitions *****/
void *mainThread(void *arg0)
{
    /* Initialize and open UART */
    UART2_Handle uart;
    UART2_Params uartParams;
    UART2_Params_init(&uartParams);
    uartParams.baudRate = 115200;
    uart = UART2_open(CONFIG_UART2_0, &uartParams);

    /* Initialize and open RCL */
    RCL_init();
    RCL_Handle rclHandle = RCL_open(&rclClient, &LRF_config);

    /* Set RF frequency */
    rclContRxCmdGenericRx.rfFrequency = FREQUENCY;

    /* Start command as soon as possible */
    rclContRxCmdGenericRx.common.scheduling = RCL_Schedule_Now;
    rclContRxCmdGenericRx.common.status = RCL_CommandStatus_Idle;

    /* Prevent start of packet detection */
    rclContRxCmdGenericRx.config.disableSyncA = 1;
    rclContRxCmdGenericRx.config.disableSyncB = 1;

    /* Callback triggers on last command done */
    rclContRxCmdGenericRx.common.runtime.callback = defaultCallback;
    rclContRxCmdGenericRx.common.runtime.rclCallbackMask.value = RCL_EventLastCmdDone.value;

    /* Submit command */
    RCL_Command_submit(rclHandle, &rclContRxCmdGenericRx);

    /* Loop forever */
    while (1)
    {
        size_t uartBytesWritten = 0;
        char uartLineBuffer[4 + 2 + 1]; // Worst-case length: -128\r\n\0
        int8_t rssiValue;

        /* Iteration delay */
        usleep(RSSI_INTERVAL_US);

        /* Read RSSI value */
        rssiValue = RCL_readRssi();

        /* Print as text over UART, one RSSI value per line */
        sprintf(uartLineBuffer, "%d\r\n", rssiValue);
        UART2_write(uart, uartLineBuffer, strlen(uartLineBuffer), &uartBytesWritten);
    }
}
